static void g6r_tick(volatile long long* n)
{
    static volatile long once;
    if (!__atomic_exchange_n(&once, 1, __ATOMIC_RELAXED)) atexit(g6r_report);
    if (!(__atomic_add_fetch(n, 1, __ATOMIC_RELAXED) & 0xFFFFF)) g6r_report();
}
#define G6R_COUNT(n, k) do { if (g6r_stats_on()) g6r_tick(&s_##n##_##k); } while (0)

